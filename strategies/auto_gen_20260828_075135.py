@dataclass(slots=True)
class StrategyConfig:
    """Runtime configuration — all values injected, no hardcoded defaults."""
    symbol: str
    base_capital: float                    # Quote currency allocated to this bot
    grid_spacing_pct: float                # Distance between grid levels (e.g., 0.005 = 0.5%)
    grid_levels: int                       # Number of levels on each side of center
    momentum_window: int                   # Bars for momentum calculation
    momentum_threshold: float              # |momentum| > threshold → pause grid
    volatility_window: int                 # Bars for ATR/volatility estimation
    volatility_scale: float                # Multiplier for dynamic spacing
    min_spacing_pct: float                 # Floor for grid_spacing_pct
    max_spacing_pct: float                 # Ceiling for grid_spacing_pct
    rebalance_interval_sec: int            # Seconds between center re-anchoring
    order_size_quote: float                # Quote amount per grid level
