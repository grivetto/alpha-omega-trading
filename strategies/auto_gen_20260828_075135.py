@dataclass(slots=True)
class GridLevel:
    """Single grid level state."""
    price: float
    side: str                      # "buy" or "sell"
    order_id: Optional[str] = None
    filled: bool = False
    fill_price: float = 0.0
    fill_qty: float = 0.0


@dataclass(slots=True)
class StrategyState:
    """Mutable runtime state."""
    center_price: float = 0.0
    levels: list[GridLevel] = field(default_factory=list)
    price_history: deque = field(default_factory=lambda: deque(maxlen=1000))
    last_rebalance_ts: float = 0.0
    grid_paused: bool = False
    current_spacing_pct: float = 0.0
    realized_pnl: float = 0.0
    unrealized_pnl: float = 0.0
    total_fees: float = 0.0


class StrategyBase:
    """
    Adaptive Grid-Momentum Hybrid Strategy.

    Architecture:
    - on_tick: called on every price update (streaming, O(1) amortized)
    - on_fill: called when an order fills
    - validate_config: static validation
    - estimate_memory_mb: static memory footprint estimate
    """

    def __init__(self, config: StrategyConfig) -> None:
        self.config = config
        self.state = StrategyState()
        self.config.validate()
        self.state.current_spacing_pct = config.grid_spacing_pct
        self._momentum_buffer: deque[float] = deque(maxlen=config.momentum_window)
        self._volatility_buffer: deque[float] = deque(maxlen=config.volatility_window)

    # ─── Public Interface ────────────────────────────────────────────────

    def on_tick(self, timestamp: float, price: float, volume: float = 0.0) -> list[dict[str, Any]]:
        """
        Process a new market tick. Returns list of order actions to execute.
        Streaming-friendly: O(1) amortized, no allocations in hot path.
        """
        actions: list[dict[str, Any]] = []

        # Update price history (bounded deque → no OOM)
        self.state.price_history.append(price)
        self._momentum_buffer.append(price)
        self._volatility_buffer.append(price)

        # Initialize center on first tick
        if self.state.center_price == 0.0:
            self.state.center_price = price
            self._build_initial_grid()
            self.state.last_rebalance_ts = timestamp
            return actions

        # Rebalance center price periodically
        if timestamp - self.state.last_rebalance_ts >= self.config.rebalance_interval_sec:
            actions.extend(self._rebalance_center(price, timestamp))

        # Update dynamic spacing based on volatility
        self._update_spacing()

        # Momentum filter
        momentum = self._compute_momentum()
        if abs(momentum) > self.config.momentum_threshold:
            if not self.state.grid_paused:
                self.state.grid_paused = True
                actions.append({"type": "cancel_all", "reason": f"momentum_pause: {momentum:.4f}"})
        else:
            if self.state.grid_paused:
                self.state.grid_paused = False
                actions.append({"type": "resume_grid", "reason": f"momentum_resume: {momentum:.4f}"})

        # Manage open orders (replace filled, maintain grid)
        if not self.state.grid_paused:
            actions.extend(self._manage_grid(price))

        return actions

    def on_fill(self, order_id: str, side: str, price: float, qty: float, fee: float) -> list[dict[str, Any]]:
        """
        Process a fill event. Returns any follow-up actions (e.g., place opposite order).
        """
        actions: list[dict[str, Any]] = []
        self.state.total_fees += fee

        # Find and update the level
        for level in self.state.levels:
            if level.order_id == order_id:
                level.filled = True
                level.fill_price = price
                level.fill_qty = qty
                level.order_id = None

                # Realized PnL for round-trips
                if side == "sell":
                    # Find matching buy
                    for buy_level in self.state.levels:
                        if buy_level.side == "buy" and buy_level.filled and buy_level.fill_qty > 0:
                            match_qty = min(qty, buy_level.fill_qty)
                            pnl = (price - buy_level.fill_price) * match_qty - fee
                            self.state.realized_pnl += pnl
                            buy_level.fill_qty -= match_qty
                            qty -= match_qty
                            if qty <= 0:
                                break

                # Place opposite order to maintain grid symmetry
                opposite_side = "sell" if side == "buy" else "buy"
                opposite_price = price * (1 + self.state.current_spacing_pct if opposite_side == "sell" else 1 - self.state.current_spacing_pct)
                actions.append({
                    "type": "place_order",
                    "side": opposite_side,
                    "price": opposite_price,
                    "quote_amount": self.config.order_size_quote,
                    "tag": f"grid_replace_{side}"
                })
                break

        return actions

    @staticmethod
    def validate_config(config_dict: dict[str, Any]) -> StrategyConfig:
        """Validate and construct StrategyConfig from dict."""
        return StrategyConfig(**config_dict)

    @staticmethod
    def estimate_memory_mb(config: StrategyConfig) -> float:
        """
        Estimate peak memory usage in MB.
        Components:
        - price_history: maxlen=1000 floats ~ 8 KB
        - momentum_buffer: maxlen=momentum_window floats
        - volatility_buffer: maxlen=volatility_window floats
        - levels: 2 * grid_levels GridLevel objects
        - Overhead: ~2 MB base
        """
        history_mb = (1000 * 8) / 1_048_576
        momentum_mb = (config.momentum_window * 8) / 1_048_576
        volatility_mb = (config.volatility_window * 8) / 1_048_576
        levels_mb = (config.grid_levels * 2 * 200) / 1_048_576  # ~200 bytes per GridLevel
        return round(2.0 + history_mb + momentum_mb + volatility_mb + levels_mb, 2)

    # ─── Internal Helpers ────────────────────────────────────────────────

    def _build_initial_grid(self) -> None:
        """Build symmetric grid around center_price."""
        self.state.levels.clear()
        spacing = self.state.current_spacing_pct
        for i in range(1, self.config.grid_levels + 1):
            buy_price = self.state.center_price * (1 - spacing * i)
            sell_price = self.state.center_price * (1 + spacing * i)
            self.state.levels.append(GridLevel(price=buy_price, side="buy"))
            self.state.levels.append(GridLevel(price=sell_price, side="sell"))

    def _rebalance_center(self, price: float, timestamp: float) -> list[dict[str, Any]]:
        """Re-anchor grid center to current price, cancel/replace orders."""
        actions: list[dict[str, Any]] = []
        old_center = self.state.center_price
        self.state.center_price = price
        self.state.last_rebalance_ts = timestamp

        # Cancel all open orders
        for level in self.state.levels:
            if level.order_id is not None:
                actions.append({"type": "cancel_order", "order_id": level.order_id})
                level.order_id = None

        # Rebuild grid
        self._build_initial_grid()
        actions.append({"type": "log", "msg": f"rebalanced: {old_center:.4f} -> {price:.4f}"})
        return actions

    def _update_spacing(self) -> None:
        """Adjust grid spacing based on recent volatility (ATR-like)."""
        if len(self._volatility_buffer) < self.config.volatility_window:
            return

        # True Range approximation: max(high-low, |high-prev_close|, |low-prev_close|)
        prices = list(self._volatility_buffer)
        true_ranges = []
        for i in range(1, len(prices)):
            tr = abs(prices[i] - prices[i-1])
            true_ranges.append(tr)

        if not true_ranges:
            return

        atr = sum(true_ranges) / len(true_ranges)
        atr_pct = atr / self.state.center_price
        new_spacing = atr_pct * self.config.volatility_scale
        new_spacing = max(self.config.min_spacing_pct, min(self.config.max_spacing_pct, new_spacing))

        if abs(new_spacing - self.state.current_spacing_pct) > self.state.current_spacing_pct * 0.1:
            self.state.current_spacing_pct = new_spacing
            # Grid will be rebuilt on next rebalance

    def _compute_momentum(self) -> float:
        """Linear regression slope normalized by price (momentum)."""
        if len(self._momentum_buffer) < self.config.momentum_window:
            return 0.0

        prices = list(self._momentum_buffer)
        n = len(prices)
        x_mean = (n - 1) / 2.0
        y_mean = sum(prices) / n

        num = sum((i - x_mean) * (prices[i] - y_mean) for i in range(n))
        den = sum((i - x_mean) ** 2 for i in range(n))

        if den == 0:
            return 0.0

        slope = num / den
        return slope / y_mean  # Normalized momentum

    def _manage_grid(self, current_price: float) -> list[dict[str, Any]]:
        """Place missing orders, respecting position limits."""
        actions: list[dict[str, Any]] = []

        # Estimate current position
        base_qty = sum(
            lvl.fill_qty for lvl in self.state.levels if lvl.side == "buy" and lvl.filled
        ) - sum(
            lvl.fill_qty for lvl in self.state.levels if lvl.side == "sell" and lvl.filled
        )

        max_base = (self.config.base_capital * self.config.max_position_pct) / current_price

        for level in self.state.levels:
            if level.order_id is not None:
                continue  # Order already live

            if level.filled and level.fill_qty == 0:
                continue  # Fully matched

            # Position limit check
            if level.side == "buy" and base_qty >= max_base:
                continue
            if level.side == "sell" and base_qty <= -max_base:
                continue

            # Price validity (don't buy above center, don't sell below)
            if level.side == "buy" and level.price >= self.state.center_price:
                continue
            if level.side == "sell" and level.price <= self.state.center_price:
                continue

            actions.append({
                "type": "place_order",
                "side": level.side,
                "price": level.price,
                "quote_amount": self.config.order_size_quote,
                "tag": "grid_maintain"
            })

        return actions

    # ─── Introspection ──────────────────────────────────────────────────

    def get_state_snapshot(self) -> dict[str, Any]:
        """Return serializable state for monitoring."""
        return {
            "center_price": self.state.center_price,
            "current_spacing_pct": self.state.current_spacing_pct,
            "grid_paused": self.state.grid_paused,
            "levels": [
                {
                    "price": lvl.price,
                    "side": lvl.side,
                    "filled": lvl.filled,
                    "fill_price": lvl.fill_price,
                    "fill_qty": lvl.fill_qty,
                    "has_order": lvl.order_id is not None
                }
                for lvl in self.state.levels
            ],
            "realized_pnl": self.state.realized_pnl,
            "unrealized_pnl": self.state.unrealized_pnl,
            "total_fees": self.state.total_fees,
            "price_history_len": len(self.state.price_history)
        }


