    def _zscore(self) -> float:
        snap: List[float] = self._prices.snapshot()
        if len(snap) < int(self.config["hurst_window"]):
            return 0.0
        last: float = snap[-1]
        mean: float = statistics.fmean(snap)
        sd: float = statistics.pstdev(snap)
        if sd <= 0.0:
            return 0.0
        return (last - mean) / sd

