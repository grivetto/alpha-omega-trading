        snap: List[float] = self._returns.snapshot()
        if len(snap) < int(self.config["hurst_window"]):
            return self._mode  # not enough data yet
        h: float = _hurst_exponent(snap)
        if math.isnan(h):
            return self._mode
        mh: float = float(self.config["momentum_hurst"])
