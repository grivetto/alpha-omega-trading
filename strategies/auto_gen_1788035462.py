    def _close(self, reason: str) -> Dict[str, Any]:
        self._open_qty = 0.0
        self._entry_price = None
        return {
            "action": "close",
            "symbol": self.config["symbol"],
            "reason": reason,
        }

    def _realized_pnl(self, exit_price: float) -> float:
        if self._entry_price is None or self._open_qty <= 0.0:
            return 0.0
        side_mult: float = 1.0 if self._entry_price <= exit_price else -1.0
        return side_mult * self._open_qty * abs(exit_price - self._entry_price)

    def on_fill(self, fill: Dict[str, Any]) -> None:
        self._fills += 1


