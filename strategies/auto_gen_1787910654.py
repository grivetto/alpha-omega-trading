@dataclass(frozen=True, slots=True)
class StrategyConfig:
    """Configuration for AdaptiveGridMomentum strategy."""
    symbol: str
    base_capital: float
    grid_levels: int = 10
    base_spacing_pct: float = 0.008  # 0.8% base spacing
    atr_period: int = 14
    atr_multiplier: float = 1.5
    momentum_lookback: int = 20
    momentum_threshold: float = 0.015  # 1.5% momentum to pause grid
    max_position_pct: float = 0.8  # max 80% of capital in position
    min_order_size: float = 10.0  # minimum order size in quote currency
    fee_rate: float = 0.0016  # maker fee (Kraken default)
    enable_momentum_filter: bool = True
    rebalance_interval_sec: int = 300  # 5 min rebalance check

    def validate(self) -> None:
        if self.base_capital <= 0:
            raise ValueError("base_capital must be positive")
        if self.grid_levels < 2:
            raise ValueError("grid_levels must be >= 2")
        if not 0 < self.base_spacing_pct < 0.1:
            raise ValueError("base_spacing_pct must be in (0, 0.1)")
        if self.atr_period < 2:
            raise ValueError("atr_period must be >= 2")
        if self.momentum_lookback < 5:
            raise ValueError("momentum_lookback must be >= 5")
        if not 0 < self.max_position_pct <= 1:
            raise ValueError("max_position_pct must be in (0, 1]")


@dataclass(slots=True)
class GridLevel:
    """Single grid level with order tracking."""
    price: float
    side: str  # 'buy' or 'sell'
    order_id: Optional[str] = None
    filled: bool = False
    filled_qty: float = 0.0
    filled_price: float = 0.0


@dataclass(slots=True)
class MarketState:
    """Rolling market state for streaming calculation."""
    prices: deque = field(default_factory=lambda: deque(maxlen=200))
    highs: deque = field(default_factory=lambda: deque(maxlen=200))
    lows: deque = field(default_factory=lambda: deque(maxlen=200))
    volumes: deque = field(default_factory=lambda: deque(maxlen=200))
    atr: float = 0.0
    momentum: float = 0.0
    fair_value: float = 0.0

    def update(self, price: float, high: float, low: float, volume: float) -> None:
        self.prices.append(price)
        self.highs.append(high)
        self.lows.append(low)
        self.volumes.append(volume)
        self._recalc()

    def _recalc(self) -> None:
        if len(self.prices) < 2:
            return
        # ATR calculation (streaming)
        if len(self.highs) >= self.atr_period + 1:
            tr_sum = 0.0
            for i in range(-self.atr_period, 0):
                tr = max(
                    self.highs[i] - self.lows[i],
                    abs(self.highs[i] - self.prices[i - 1]),
                    abs(self.lows[i] - self.prices[i - 1])
                )
                tr_sum += tr
            self.atr = tr_sum / self.atr_period
        # Momentum: (price_now / price_lookback_ago) - 1
        if len(self.prices) >= self.momentum_lookback:
            self.momentum = (self.prices[-1] / self.prices[-self.momentum_lookback]) - 1
        # Fair value: VWAP over recent window
        vwap_window = min(50, len(self.prices))
        pv_sum = sum(self.prices[-i] * self.volumes[-i] for i in range(1, vwap_window + 1))
        vol_sum = sum(self.volumes[-i] for i in range(1, vwap_window + 1))
        self.fair_value = pv_sum / vol_sum if vol_sum > 0 else self.prices[-1]

    # These will be set by strategy instance
    atr_period: int = 14
    momentum_lookback: int = 20


