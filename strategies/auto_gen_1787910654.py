class AdaptiveGridMomentum(StrategyBase):
    """
    Adaptive Grid with Momentum Filter.
    
    Features:
    - Dynamic grid spacing based on ATR
    - Momentum filter pauses new grid orders during strong trends
    - Capital recycling: filled orders become new opposite-side levels
    - Streaming calculation - O(1) memory per tick
    """

    def __init__(self, config: StrategyConfig) -> None:
        super().__init__(config)
        self._grid_initialized: bool = False

    def _init_grid(self, fair_value: float, spacing: float) -> None:
        """Initialize grid levels around fair value."""
        self.grid.clear()
        half = self.config.grid_levels // 2
        for i in range(-half, half + 1):
            if i == 0:
                continue
            level_price = fair_value * (1 + i * spacing)
            side = 'buy' if i < 0 else 'sell'
            self.grid.append(GridLevel(price=level_price, side=side))
        self._grid_initialized = True

    def _calculate_dynamic_spacing(self) -> float:
        """Calculate grid spacing based on ATR."""
        if self.state.atr <= 0 or self.state.fair_value <= 0:
            return self.config.base_spacing_pct
        atr_pct = self.state.atr / self.state.fair_value
        # Scale base spacing by ATR, clamp to reasonable bounds
        dynamic = self.config.base_spacing_pct * max(0.5, min(3.0, atr_pct / 0.02))
        return max(0.003, min(0.03, dynamic))  # 0.3% - 3% bounds

    def _should_pause_grid(self) -> bool:
        """Check if momentum filter should pause grid."""
        if not self.config.enable_momentum_filter:
            return False
        return abs(self.state.momentum) > self.config.momentum_threshold

    def _generate_orders(
        self,
        price: float,
        free_quote: float,
        free_base: float
    ) -> list[dict]:
        """Generate order actions for current grid state."""
        orders = []
        spacing = self._calculate_dynamic_spacing()
        
        if not self._grid_initialized:
            self._init_grid(self.state.fair_value, spacing)
            return orders

        # Check if we need to rebalance grid (fair value shifted)
        current_center = (self.grid[0].price + self.grid[-1].price) / 2
        if abs(current_center - self.state.fair_value) / self.state.fair_value > spacing * 0.5:
            # Re-center grid
            self._init_grid(self.state.fair_value, spacing)
            return orders

        # Place/move orders for unfilled levels
        max_position_value = self.config.base_capital * self.config.max_position_pct
        current_position_value = abs(self.position) * price
        
        for level in self.grid:
            if level.filled or level.order_id is not None:
                continue
            
            # Check capital constraints
            if level.side == 'buy':
                required_quote = level.price * self.config.min_order_size / price
                if required_quote > free_quote * 0.9:  # keep 10% buffer
                    continue
                if current_position_value + required_quote > max_position_value:
                    continue
            else:  # sell
                required_base = self.config.min_order_size / price
                if required_base > free_base * 0.9:
                    continue
            
            # Momentum filter: pause new orders against trend
            if self._should_pause_grid():
                if (level.side == 'buy' and self.state.momentum < 0) or \
                   (level.side == 'sell' and self.state.momentum > 0):
                    continue
            
            orders.append({
                'symbol': self.config.symbol,
                'side': level.side,
                'price': round(level.price, 5),
                'amount': round(self.config.min_order_size / level.price, 6),
                'type': 'limit',
                'post_only': True,
                'meta': {'grid_level': True, 'spacing_pct': spacing}
            })
        
        return orders

    def on_tick(
        self,
        timestamp: float,
        price: float,
        high: float,
        low: float,
        volume: float,
        free_quote: float,
        free_base: float
    ) -> list[dict]:
        """Process market tick - streaming, O(1) memory."""
        self.state.update(price, high, low, volume)
        
        # Periodic garbage collection for long-running processes
        if int(timestamp) % 3600 == 0:
            gc.collect()
        
        return self._generate_orders(price, free_quote, free_base)

    def on_fill(self, order_id: str, side: str, price: float, qty: float, fee: float) -> None:
        """Handle fill: update position, recycle grid level."""
        self.total_fees += fee
        
        # Find and update grid level
        for level in self.grid:
            if level.order_id == order_id:
                level.filled = True
                level.filled_qty = qty
                level.filled_price = price
                break
        
        # Update position
        if side == 'buy':
            self.position += qty
            self.realized_pnl -= fee
        else:
            self.position -= qty
            self.realized_pnl -= fee
        
        # Recycle: create new opposite level at filled price * (1 ± spacing)
        spacing = self._calculate_dynamic_spacing()
        if side == 'buy':
            # Filled buy -> place sell above
            new_price = price * (1 + spacing)
            new_side = 'sell'
        else:
            # Filled sell -> place buy below
            new_price = price * (1 - spacing)
            new_side = 'buy'
        
        # Replace filled level with new recycled level
        for i, level in enumerate(self.grid):
            if level.order_id == order_id:
                self.grid[i] = GridLevel(price=new_price, side=new_side)
                break
        
        # Update unrealized PnL
        self.unrealized_pnl = self.position * (price - self.state.fair_value)


def generate_synthetic_data(
    n: int = 1000,
    start_price: float = 100.0,
    volatility: float = 0.02,
    trend: float = 0.0001
) -> Generator[tuple[float, float, float, float, float], None, None]:
    """Generate synthetic OHLCV data for testing. Memory efficient generator."""
    import random
    price = start_price
    for i in range(n):
        # Random walk with drift
        change = random.gauss(trend, volatility)
        price *= (1 + change)
        
        # Generate OHLC from price
        high = price * (1 + abs(random.gauss(0, volatility * 0.5)))
        low = price * (1 - abs(random.gauss(0, volatility * 0.5)))
        volume = random.uniform(100, 10000)
        
        yield (float(i), price, high, low, volume)
    
    # Explicit cleanup
    del price, change, high, low, volume
    gc.collect()


