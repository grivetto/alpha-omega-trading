    win_rate: float = 0.55         # prior; updated online
    rr_ratio: float = 1.8          # reward:risk for Kelly sizing
    sl_atr: float = 1.2            # stop-loss offset (ATR units)
    tp_atr: float = 2.0            # take-profit offset (ATR units)
    max_loss_pct: float = 0.03     # max loss per position as % of capital
    cooldown_ticks: int = 12       # min ticks between two fades
    max_wins_buffer: int = 2048    # bounded feedback deque (OOM guard)
    gc_every: int = 5000           # periodic gc trigger (0 = off)

    def __post_init__(self) -> None:
        self.validate()

    def validate(self) -> None:
        """Validate ranges; raise ConfigError on bad values."""
        if self.ewma_span < 2 or self.anchor_span < 2:
            raise ConfigError("ewma_span and anchor_span must be >= 2")
