        size_frac = self._target_size_frac()
        spacing = float(cfg["base_spacing_pct"]) / max(size_frac, 0.05)
        st.levels = int(cfg["max_levels"])
        st.spacing = spacing
        st.regime = "vtk_vol={:.5f}_size={:.2f}".format(st.vol_ewma, size_frac)

        if st.last_price is None:
            st.last_price = price
            st.pending.append(price * (1.0 - spacing))
            return {"action": "hold", "spacing": spacing,
                    "levels": st.levels, "size_frac": size_frac}

