        lowest = st.pending[0] if st.pending else st.last_price
        if price <= lowest * (1.0 - spacing):
            qty = (free_quote * size_frac) / price
            st.pending.append(price * (1.0 - spacing))
            return {"action": "buy", "price": price, "qty": qty,
                    "spacing": spacing, "levels": st.levels}

