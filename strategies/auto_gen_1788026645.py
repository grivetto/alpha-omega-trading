def _ewma(prev: float, new_val: float, span: float) -> float:
    """O(1) EWMA update."""
    if span <= 1.0:
        return new_val
    alpha = 2.0 / (span + 1.0)
    return alpha * new_val + (1.0 - alpha) * prev


